#!/usr/bin/env node
/**
 * Generates docs/ASO_LOCALIZATIONS.md from scripts/aso/listings.mjs and refuses to
 * write it if any field breaks Apple's rules.
 *
 *   node scripts/aso-localizations.mjs          # check and write
 *   node scripts/aso-localizations.mjs --check  # check only, exit 1 on any problem
 *
 * Lengths are counted the way App Store Connect counts them: UTF-16 code units.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { check, LIMITS } from './aso/check.mjs';
import { LISTINGS } from './aso/listings.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'docs', 'ASO_LOCALIZATIONS.md');

function row(field, value, limit) {
  return `| ${field} | \`${value.replaceAll('|', '\\|')}\` | ${value.length}/${limit} |`;
}

function render() {
  const lines = [
    '# App Store localizations',
    '',
    '<!-- Generated by scripts/aso-localizations.mjs from scripts/aso/listings.mjs. Do not edit by hand. -->',
    '',
    'Every field below has been checked by the generator: Apple\'s length limits (counted in',
    'UTF-16 code units, as App Store Connect counts them), no whitespace or repeated stems in',
    'the keyword field, no keyword that repeats a name or subtitle word, no trademarks in an',
    'indexed field, and no exclamation marks anywhere.',
    '',
    'Paste each block exactly. Copy from the fenced blocks, not from a wrapped preview.',
    '',
    '| Locale | Store | Status |',
    '|---|---|---|',
    ...LISTINGS.map((l) => `| ${l.locale} | ${l.store} | ${l.status} |`),
    '',
    'Status: **live** is in App Store Connect now and is being changed; **new** has to be added;',
    '**draft** must be checked by a native speaker before it ships.',
    '',
  ];

  for (const l of LISTINGS) {
    lines.push(`## ${l.locale} — ${l.store}`, '');
    lines.push('| Field | Value | Length |', '|---|---|---|');
    lines.push(row('Name', l.name, LIMITS.name));
    lines.push(row('Subtitle', l.subtitle, LIMITS.subtitle));
    lines.push(row('Keywords', l.keywords, LIMITS.keywords));
    lines.push(`| Promotional text | see below | ${l.promo.length}/${LIMITS.promo} |`);
    lines.push(`| Description | see below | ${l.description.length}/${LIMITS.description} |`);
    lines.push('');
    lines.push('**Why**', '');
    for (const reason of l.whyItChanged) lines.push(`- ${reason}`);
    lines.push('', '**Promotional text**', '', '```text', l.promo, '```', '');
    lines.push('**Description**', '', '```text', l.description, '```', '');
    lines.push(`**What's New in 1.1** (${l.whatsNew.length}/${LIMITS.whatsNew})`, '', '```text', l.whatsNew, '```', '');
  }
  return lines.join('\n');
}

const failures = LISTINGS.flatMap((l) => check(l).map((p) => `${l.locale}: ${p}`));
if (failures.length > 0) {
  console.error('Listing copy breaks the rules:\n' + failures.map((f) => `  - ${f}`).join('\n'));
  process.exit(1);
}

for (const l of LISTINGS) {
  console.log(
    `${l.locale.padEnd(6)} name ${l.name.length}/30  subtitle ${l.subtitle.length}/30  ` +
      `keywords ${l.keywords.length}/100  promo ${l.promo.length}/170  description ${l.description.length}/4000`
  );
}

if (!process.argv.includes('--check')) {
  writeFileSync(out, render() + '\n');
  console.log(`wrote ${out}`);
}
